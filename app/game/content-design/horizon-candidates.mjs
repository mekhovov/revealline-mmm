export function createOpeningCandidates({ artwork = false } = {}) {
  const project = createStarterProject('horizon-greybox-candidates');
  project.name = 'Prologue + Horizon · greybox candidates';
  project.maps = [];
  if (artwork) project.assets = structuredClone(HORIZON_ART_CANDIDATES);
  project.missions = candidates.map((candidate) => {
    const template = createStarterProject().missions[0];
    const map = {
      format: 'MapDesignV1',
      id: `${candidate.id}-map`,
      revision: 'greybox-1',
      name: candidate.name,
      width: 72,
      height: 36,
      walls: [],
      foundations: structuredClone(candidate.foundations),
      terrain: [],
      spawns: [{ id: 'home', x: candidate.spawn[0] + 0.5, y: candidate.spawn[1] + 0.5 }],
    };
    project.maps.push(map);
    return {
      ...template,
      id: candidate.id,
      revision: 'greybox-1',
      name: candidate.name,
      map: { id: map.id, revision: map.revision },
      actors: structuredClone(candidate.actors),
      coverage: candidate.coverage,
      presentation: {
        ...template.presentation,
        backgroundAssetId: artwork ? `horizon-${candidate.id}` : null,
      },
      design: {
        ...template.design,
        routeDecision: candidate.decision,
        lesson: candidate.lesson,
        counterplay:
          'Watch each keeper before departing; close early when its path threatens the line.',
        captureConsequence: candidate.consequence,
        memorableMoment: candidate.moment,
        mastery: candidate.mastery,
        introduces: [...candidate.introduces],
        practices: [...candidate.practices],
        combines: [...candidate.combines],
        durationSeconds: [...candidate.duration],
        difficulty: {
          band: candidate.band,
          planning: candidate.band,
          execution: candidate.band,
          threatDensity: candidate.actors.length,
          timePressure: 0,
          mechanicLoad: candidate.band,
          coordination: 0,
        },
      },
    };
  });
  project.campaigns = [
    {
      format: 'CampaignDesignV1',
      id: 'prologue',
      revision: 'greybox-1',
      name: 'Prologue',
      band: 1,
      missionIds: candidates.slice(0, 3).map((m) => m.id),
    },
    {
      format: 'CampaignDesignV1',
      id: 'horizon-school',
      revision: 'greybox-1',
      name: 'Horizon School',
      band: 1,
      missionIds: candidates.slice(3, 9).map((m) => m.id),
    },
    {
      format: 'CampaignDesignV1',
      id: 'horizon-remixes',
      revision: 'greybox-1',
      name: 'Horizon Remix · optional',
      band: 2,
      missionIds: ['horizon-remix'],
    },
  ];
  project.packs = [
    {
      format: 'PackDesignV1',
      id: 'journey-opening',
      revision: 'greybox-1',
      name: 'Opening candidates',
      campaignIds: ['prologue', 'horizon-school'],
    },
    {
      format: 'PackDesignV1',
      id: 'opening-remixes',
      revision: 'greybox-1',
      name: 'Optional opening Remix',
      campaignIds: ['horizon-remixes'],
    },
  ];
  return project;
}

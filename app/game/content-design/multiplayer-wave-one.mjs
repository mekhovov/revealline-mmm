import { freezeDesign } from './catalogs.mjs';

// Every rectangle and opening below is authored independently. Shared helpers
// only provide the data envelope; they do not rotate, scale or randomize maps.
function stage(
  chapter,
  mode,
  id,
  name,
  foundations,
  walls,
  spawns,
  keepers,
  decision,
  consequence,
  extras = {},
) {
  return {
    chapter,
    mode,
    id,
    name,
    foundations,
    walls,
    spawns,
    keepers,
    decision,
    consequence,
    coverage: mode === 'team' ? 0.6 : 0.58,
    moment: consequence,
    mastery:
      mode === 'team'
        ? 'Both pilots bank a cut and use a return opened by their partner, without a knockdown.'
        : 'Complete the race using both opening plans on separate attempts.',
    ...extras,
  };
}

